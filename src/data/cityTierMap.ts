/**
 * 根据城市名获取城市级别
 * @param city 城市名
 * @returns 城市级别，未知城市返回 'other'
 */
export function getCityTier(city: string): CityTier {
  return CITY_TO_TIER[city] || 'other';
}

/**
 * 根据城市名获取城市级别的显示名称
 * @param city 城市名
 * @returns 城市级别显示名称，未知城市返回 '其他'
 */
export function getCityTierLabel(city: string): string {
  const tier = getCityTier(city);
  return CITY_TIER_LABELS[tier];
}